// Offline-only generation from the committed, unmodified 12dicts source.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceHash = 'ad7b041b98e09a30ae9f4938ac24ca919a434b021a6b8582a69ad5d4863dabf0';
const defaultSource = resolve(root, 'vendor/wordlists/12dicts/3of6game.txt');
const defaultOutput = resolve(root, 'src/data/boggle-dictionary.generated.ts');
const { values } = parseArgs({ options: {
  source: { type: 'string' }, output: { type: 'string' }, check: { type: 'boolean', default: false },
} });

try {
  const source = resolve(values.source ?? defaultSource);
  const output = resolve(values.output ?? defaultOutput);
  const bytes = readFileSync(source);
  const hash = createHash('sha256').update(bytes).digest('hex');
  if (source === defaultSource && hash !== sourceHash) {
    throw new Error(`Vendored 12dicts source SHA-256 mismatch: ${hash}`);
  }
  const words = [...new Set(bytes.toString('utf8').split(/\r?\n/)
    .map(line => line.trim().replace(/[!+&^$]+$/, '').toUpperCase())
    .filter(word => /^[A-Z]{3,}$/.test(word)))].sort();
  for (const sentinel of ['CAT', 'QUIT', 'SEE', 'ZYGOTE']) {
    if (!words.includes(sentinel)) throw new Error(`Missing required dictionary word: ${sentinel}`);
  }
  const generated = '// Generated by scripts/build-boggle-dictionary.mjs; do not edit.\n'
    + '// Alan Beale, 12dicts 6.0.2 3of6game (public domain). See vendor/wordlists/12dicts/README.md.\n'
    + `// Source SHA-256: ${hash}; playable words: ${words.length}.\n`
    + `export const BOGGLE_WORDS = ${JSON.stringify(words.join('\n'))};\n`;
  if (values.check) {
    let current;
    try { current = readFileSync(output, 'utf8'); } catch { /* Missing output is stale too. */ }
    if (current !== generated) throw new Error('Boggle dictionary output is stale; run npm run dictionary:boggle.');
  } else {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, generated);
  }
  console.log(`[dictionary:boggle] ${values.check ? 'checked' : 'generated'} ${words.length} words (${Buffer.byteLength(generated)} bytes)`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
